// Русская типографика: короткие предлоги, союзы и частицы не остаются в конце строки.
const SHORT = 'а|в|во|и|к|ко|о|об|от|с|со|у|из|на|по|за|до|не|ни|для|под|над|при|без|про|что|как|но|же|ли'
const RE = new RegExp(`(^|[\\s(«])(${SHORT})\\s+`, 'giu')

export function nbsp(text: string): string {
  // Два прохода: цепочки вроде «и в» склеиваются целиком.
  return text.replace(RE, '$1$2 ').replace(RE, '$1$2 ')
}
