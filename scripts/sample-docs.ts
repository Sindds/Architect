/** График этапов: срок, дни от начала, доля и сумма платежа. */
function stagesTable() {
  let day = 0
  const rows = STEPS.map((s, i) => {
    const from = day + 1
    day += s.days
    const amount = Math.round((b.total * s.paymentPercent) / 100)
    return `<tr><td class="n">${i + 1}</td><td><b>${s.title}</b><br><span class="note">${s.result}</span></td><td class="r">${from}–${day}</td><td class="r">${formatDays(s.days)}</td><td class="r">${s.paymentPercent}%</td><td class="r">${formatRub(amount)}</td></tr>`
  }).join('')
  return `<table><thead><tr><th>№</th><th>Этап и результат</th><th class="r">Дни</th><th class="r">Срок</th><th class="r">Доля</th><th class="r">Платёж</th></tr></thead><tbody>${rows}
<tr class="total"><td></td><td>Итого</td><td></td><td class="r">${formatDays(b.days)}</td><td class="r">100%</td><td class="r">${formatRub(b.total)}</td></tr></tbody></table>`
}

