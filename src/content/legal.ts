// Реквизиты оператора и обработчиков — только из SITE. Перед запуском тексты проверяет юрист заказчика (CONTENT-SPEC §8).
export interface LegalDoc {
  slug: 'privacy' | 'soglasie' | 'cookies'
  title: string
  description: string
  sections: { heading: string; paragraphs: string[] }[]
}

interface Party {
  name: string
  details: string
  address: string
  purpose: string
}

/** Поля SITE, из которых собираются тексты. Отдельный тип, чтобы тест мог подставить данные заказчика. */
export interface LegalSite {
  brandFull: string
  email: string
  operator: { name: string; inn: string; kpp: string; ogrn: string; address: string }
  processors: readonly Party[]
  leadRetention: string
  /** Номер счётчика Яндекс Метрики: если задан, тексты говорят об аналитике и ClientID. */
  metrikaId: string
  legalVersion: { version: string; date: string }
}

const LAW = 'закона № 152-ФЗ «О персональных данных»'

/** Реквизиты оператора одной строкой: футер, юридические страницы. */
export function operatorRequisites(site: LegalSite): string {
  const o = site.operator
  return `${o.name}, ИНН ${o.inn}, КПП ${o.kpp}, ОГРН ${o.ogrn}, адрес: ${o.address}`
}

/** Что не заполнено под заказчика. Пустой список — тексты можно публиковать. */
export function legalReadiness(site: LegalSite): string[] {
  const missing: string[] = []
  // Пусто или нули шаблона — не заполнено.
  for (const [key, value] of Object.entries(site.operator)) if (!value.trim() || /^0+$/.test(value.trim())) missing.push(`operator.${key}`)
  site.processors.forEach((p, i) => {
    for (const key of ['name', 'details', 'address', 'purpose'] as const) if (!p[key].trim()) missing.push(`processors[${i}].${key}`)
  })
  if (site.email.endsWith('example.com')) missing.push('email')
  return missing
}

