/** Портрет, который можно показать в этом режиме: сгенерированные лица — только в концепте. */
export function visiblePhoto(
  member: TeamMember,
  mode: ContentMode,
): Picture | undefined {
  if (!member.photo) return undefined;
  return member.photo.generated && mode !== "concept"
    ? undefined
    : member.photo;
}
